export const getSpeciesRarity = (speciesName: string) => {
  if (RARE_SPECIES.includes(speciesName)) return "rare";
  if (UNCOMMON_SPECIES.includes(speciesName)) return "uncommon";
  return "common";
};

export const getSpeciesXP = (speciesName: string) => {
  const rarity = getSpeciesRarity(speciesName);
  switch (rarity) {
    case "rare": return 500;
    case "uncommon": return 200;
    default: return 50;
  }
};

